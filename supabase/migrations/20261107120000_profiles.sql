-- Accounts (D50): every signed-up user gets a profile with a number for
-- the admin pages ("User 001"), a role, and a status. Accounts listed in
-- ADMIN_EMAILS become admins when they sign in (the server does that with
-- the secret key); admins can make others admins. A disabled account is
-- also banned in Supabase Auth, so it can't sign in or refresh a session.
-- Users read only their own profile; only the server (service_role)
-- writes. No emails are stored here.

create table public.profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  number bigint generated by default as identity (start with 1) unique,
  role text not null default 'user' check (role in ('admin', 'user')),
  status text not null default 'active' check (status in ('active', 'disabled')),
  created_at timestamptz not null default now(),
  last_seen_at timestamptz
);

alter table public.profiles enable row level security;

create policy "Read own profile" on public.profiles
for select to authenticated
using (user_id = (select auth.uid()));

grant select on public.profiles to authenticated;
grant all on public.profiles to service_role;

-- New accounts get a profile as they're created.
create function public.create_profile() returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (user_id, created_at)
  values (new.id, coalesce(new.created_at, now()))
  on conflict (user_id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.create_profile();

-- For row level security elsewhere: whether the caller is an active admin.
create function public.is_admin() returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where user_id = (select auth.uid()) and role = 'admin' and status = 'active'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated, service_role;

-- Existing accounts are numbered by scripts/backfill-profiles.mts, which
-- knows ADMIN_EMAILS (the owner gets 000, everyone else from 001 in
-- sign-up order); emails stay out of the repository.
